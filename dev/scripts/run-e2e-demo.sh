write_summary() {
  emit "## Summary"
  emit "Total cases: $((${#PASSED_CASES[@]} + ${#FAILED_CASES[@]}))"
  emit "Pass: ${#PASSED_CASES[@]}"
  emit "Fail: ${#FAILED_CASES[@]}"
  if [[ ${#SKIPPED_PHASES[@]} -gt 0 ]]; then
    emit "Skipped phases: ${SKIPPED_PHASES[*]}"
  fi
  if [[ ${#FAILED_CASES[@]} -gt 0 ]]; then
    emit "**Failures:**"
    for c in "${FAILED_CASES[@]}"; do
      emit "- $c"
    done
  fi
}

on_exit() {
  local code=$?
  write_summary || true
  if [[ -n "$TMP" && -d "$TMP" ]]; then
    rm -rf "$TMP"
  fi
  if [[ ${#FAILED_CASES[@]} -gt 0 || $code -ne 0 ]]; then
    echo "❌ Demo finished with ${#FAILED_CASES[@]} failure(s) (exit $code)." >&2
    exit "${code:-1}"
  fi
  echo "✅ Demo finished. ${#PASSED_CASES[@]} case(s) passed." >&2
  exit 0
}
trap on_exit EXIT

# --- helpers ------------------------------------------------------------------

die() { echo "❌ preflight failed: $1" >&2; exit 1; }
warn() { echo "⚠️  $1" >&2; }

extract_nonce_from_cookie_jar() {
  # Reads cookie jar (Netscape format), extracts the raw nonce (after the dot in <hmac>.<nonce>).
  local jar="$1"
  local cookie_value
  cookie_value=$(awk '$6 == "__Host-convos_nonce" {print $7}' "$jar")
  printf '%s' "${cookie_value##*.}"
}

issue_nonce() {
  # Issues a fresh nonce, returns the cookie jar path on stdout via output arg.
  local jar="$1"
  run_curl "issue fresh nonce" -X POST "$BASE_URL/api/v2/auth/nonce" -c "$jar"
  [[ "$LAST_STATUS" == "200" ]] || { _record_fail "issue_nonce got $LAST_STATUS"; return 1; }
}

sign_and_token() {
  # Args: case_name, expected_status, cookie_jar, deviceId, [extra signer args...].
  # Runs sign-siwe.ts, posts to /auth/token, asserts status.
  local case_name="$1"; shift
  local expected_status="$1"; shift
  local jar="$1"; shift
  local device_id="$1"; shift

  local nonce
  nonce=$(extract_nonce_from_cookie_jar "$jar")

  local siwe_json
  siwe_json=$(bun run "$SCRIPT_DIR/sign-siwe.ts" --nonce "$nonce" "$@")

  local body
  body=$(jq -nc --argjson siwe "$siwe_json" --arg deviceId "$device_id" \
    '{deviceId: $deviceId, siwe: $siwe}')

  run_curl "$case_name" \
    -X POST "$BASE_URL/api/v2/auth/token" \
    -b "$jar" \
    -H "Content-Type: application/json" \
    -d "$body"
  assert_status "$case_name" "$expected_status" "$LAST_STATUS" || return 1
}

